-- Compatibility migration for databases created before role/password support.
-- Keep this script safe to re-run: existing records and application tables are preserved.
CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255),
    perfil VARCHAR(255),
    papel VARCHAR(255),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE usuario ADD COLUMN IF NOT EXISTS senha_hash VARCHAR(255);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS perfil VARCHAR(255);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS papel VARCHAR(255);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS ativo BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Existing deployments already have this table. Defining it here also makes
-- the development/H2 schema match the production user-agent relationship.
CREATE TABLE IF NOT EXISTS agente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id),
    tipo VARCHAR(255) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    cnpj VARCHAR(255) NOT NULL
);

-- Legacy accounts had no role field; treat them as customers. Passwords remain
-- NULL because they cannot be safely reconstructed from the old schema.
UPDATE usuario SET perfil = 'CLIENTE' WHERE perfil IS NULL;

-- Map rows created by the previous app version to the deployed schema's
-- two-level role representation before JPA reads the enums.
UPDATE usuario SET papel = perfil, perfil = 'AGENTE'
WHERE perfil IN ('EMPRESA', 'BANCO');

-- In the deployed schema `perfil` is CLIENTE/AGENTE and `papel` carries the
-- specific type CLIENTE/EMPRESA/BANCO. Recover agent types from `agente.tipo`.
UPDATE usuario u
SET papel = (SELECT a.tipo FROM agente a WHERE a.usuario_id = u.id)
WHERE u.perfil = 'AGENTE'
  AND EXISTS (SELECT 1 FROM agente a WHERE a.usuario_id = u.id);
UPDATE usuario SET papel = 'CLIENTE' WHERE papel IS NULL;
