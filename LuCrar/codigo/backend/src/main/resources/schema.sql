-- Compatibility migration for databases created before role/password support.
-- Keep this script safe to re-run: existing records and application tables are preserved.
CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(255) NOT NULL UNIQUE,
    senha_hash VARCHAR(255),
    perfil VARCHAR(255)
);

ALTER TABLE usuario ADD COLUMN IF NOT EXISTS senha_hash VARCHAR(255);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS perfil VARCHAR(255);

-- Legacy accounts had no role field; treat them as customers. Passwords remain
-- NULL because they cannot be safely reconstructed from the old schema.
UPDATE usuario SET perfil = 'CLIENTE' WHERE perfil IS NULL;
